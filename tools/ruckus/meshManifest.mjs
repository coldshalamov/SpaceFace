/** Generate the tiny static manifest without pulling any mesh payload into boot evaluation. */
export function renderRuckusMeshManifest(keys) {
  if (!Array.isArray(keys) || !keys.length || new Set(keys).size !== keys.length
    || keys.some(key => typeof key !== 'string' || !/^[a-z][a-z0-9]*$/.test(key))) {
    throw new TypeError('RUCKUS mesh keys must be unique module identifiers');
  }
  return '// GENERATED by tools/ruckus/pack-model.mjs from the checked-in Blender GLBs. Do not hand-edit.\n'
    + '// Payload text moved to ruckusMeshData/<key>.js (wave-143 boot F1): each module\n'
    + '// dynamic-imports in the post-eval warm lane instead of interning ~3.4MB inside the\n'
    + '// post-gate eval task. This manifest stays on the static graph so warm keys are known.\n'
    + `export const RUCKUS_MESH_KEYS = Object.freeze(${JSON.stringify(keys)});\n`
    + '// Literal lazy imports keep route wiring inspectable without eagerly loading the payloads.\n'
    + 'export const RUCKUS_MESH_LOADERS = Object.freeze({\n'
    + keys.map(key => `  ${JSON.stringify(key)}: () => import(${JSON.stringify(`./ruckusMeshData/${key}.js`)}),\n`).join('')
    + '});\n';
}
