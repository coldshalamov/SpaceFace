const ASSETS = Object.freeze({
  body0: 'assets/characters/ruckus/ruckus-lod0.glb',
  body1: 'assets/characters/ruckus/ruckus-lod1.glb',
  body2: 'assets/characters/ruckus/ruckus-lod2.glb',
  core: 'assets/characters/ruckus/pressure-core.glb',
});

/** Generate the tiny static manifest without pulling any mesh payload into boot evaluation. */
export function renderRuckusMeshManifest(keys) {
  if (!Array.isArray(keys) || !keys.length || new Set(keys).size !== keys.length
    || keys.some(key => typeof key !== 'string' || !/^[a-z][a-z0-9]*$/.test(key) || !ASSETS[key])) {
    throw new TypeError('RUCKUS mesh keys must be unique authored asset identifiers');
  }
  return '// GENERATED by tools/ruckus/pack-model.mjs from the checked-in Blender GLBs. Do not hand-edit.\n'
    + '// Authored GLB payloads are fetched only through warmRuckusModel(), so standalone Crucible\n'
    + '// can skip unreachable Ceres assets. This manifest stays static so warm keys are known.\n'
    + `export const RUCKUS_MESH_KEYS = Object.freeze(${JSON.stringify(keys)});\n`
    + '// Literal asset paths keep demand fetches inspectable without eager payload imports.\n'
    + `export const RUCKUS_MESH_ASSETS = Object.freeze(${JSON.stringify(Object.fromEntries(keys.map(key => [key, ASSETS[key]])))});\n`;
}
