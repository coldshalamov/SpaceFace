function atom(row) {
  return Object.freeze({ ...row });
}

export function atomById(id) {
  return CAUSAL_ATOMS.find((row) => row.id === id) || null;
}

export function runnableAtoms() {
  return CAUSAL_ATOMS.filter((row) => row.runnable);
}

export function blockedAtoms() {
  return CAUSAL_ATOMS.filter((row) => !row.runnable);
}
