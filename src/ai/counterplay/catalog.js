const BY_ID = new Map(COUNTERPLAY_DOCTRINES.map((row) => [row.id, row]));

export const COUNTERPLAY_DOCTRINE_IDS = Object.freeze(COUNTERPLAY_DOCTRINES.map((row) => row.id));

export function counterplayDoctrineById(id) {
  return BY_ID.get(String(id || '')) || null;
}

export function isCounterplayDoctrineId(id) {
  return BY_ID.has(String(id || ''));
}
