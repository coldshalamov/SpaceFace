// Metres in the source XZ plane. Each convex halfspace uses n.dot(p) <= offset.
// A clearance owner may transform these to the actual site; this supplies no verdict.
export function thimbleDoorCollisionSegments() {
  return DOOR_PROXY.convexParts.map(part => {
    const vertices = part.points.map(p => ({ x: p.x * THIMBLE_DOOR_RADIUS, z: p.z * THIMBLE_DOOR_RADIUS }));
    const halfspaces = vertices.map((a, i) => {
      const b = vertices[(i + 1) % vertices.length], dx = b.x - a.x, dz = b.z - a.z;
      const length = Math.hypot(dx, dz), normal = { x: dz / length, z: -dx / length };
      return { normal, offset: normal.x * a.x + normal.z * a.z };
    });
    return { id: part.id, vertices, halfspaces };
  });
}
