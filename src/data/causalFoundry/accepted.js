const PI = Math.PI;

function scene(row) {
  return Object.freeze({
    ...row,
    player: Object.freeze({ ...row.player }),
    bodies: Object.freeze((row.bodies || []).map((body) => Object.freeze({ ...body }))),
    primary: Object.freeze({ ...row.primary }),
    alt: row.alt ? Object.freeze({ ...row.alt, then: row.alt.then ? Object.freeze({ ...row.alt.then }) : undefined }) : null,
    ablate: row.ablate ? Object.freeze({
      ...row.ablate,
      tape: row.ablate.tape ? Object.freeze({ ...row.ablate.tape }) : undefined,
    }) : null,
    expect: Object.freeze({ ...row.expect }),
    contrast: row.contrast ? Object.freeze({ ...row.contrast }) : null,
    failure: row.failure ? Object.freeze({ ...row.failure }) : null,
    varietyOn: Object.freeze(row.varietyOn || []),
    mechanics: Object.freeze(row.mechanics.slice()),
  });
}

