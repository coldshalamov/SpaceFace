export function ilexArkPhysicalBody(attachedVaultIds,revision=0){
  const attached=new Set(attachedVaultIds);
  if([...attached].some(id=>!SOCKETS[id]))throw new Error('Unknown Ilex attached vault');
  const selected=ASSEMBLIES.filter(p=>p.id==='core'||attached.has(p.id));
  const bitmap=Object.keys(SOCKETS).map(id=>attached.has(id)?'1':'0').join('');
  let inertiaY=47355.79931687074;
  for(const id of attached){const p=SOCKETS[id];inertiaY+=159+ILEX_VAULT_MASS*(p.x*p.x+p.z*p.z);}
  return {schemaVersion:1,dynamic:true,mass:ILEX_ARK_CORE_MASS+ILEX_VAULT_MASS*attached.size,
    inertiaY,radius:ILEX_ARK_RADIUS,revision,ccd:true,material:'ship',shape:'compound',
    collisionProxyManifest:{schemaVersion:1,id:'ilex-ark:source:v1:'+bitmap,referenceRadius:'radius',
      convexParts:structuredClone(selected),primitives:structuredClone(QUERIES.filter(p=>p.id==='core'||attached.has(p.id)))}};
}
