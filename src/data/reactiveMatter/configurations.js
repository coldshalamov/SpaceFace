// Sixteen authored demonstration scenes. Plain data: the witness in
// src/matter/reactive/harness.js is what moves them. Tapes are player
// operations on the XZ plane (thrust heading in radians, reel +1 in).

function scene(row) {
  return Object.freeze({
    ...row,
    crosses: Object.freeze([...row.crosses]),
    families: Object.freeze([...row.families]),
    machines: Object.freeze(row.machines.map((m) => Object.freeze({ ...m }))),
    fields: Object.freeze(row.fields.map((f) => Object.freeze({ ...f }))),
    bodies: Object.freeze(row.bodies.map((b) => Object.freeze({ ...b }))),
    hitches: Object.freeze(row.hitches.map((h) => Object.freeze({ ...h }))),
    tape: Object.freeze(row.tape.map((t) => Object.freeze({ ...t }))),
    traffic: Object.freeze((row.traffic || []).map((t) => Object.freeze({ ...t }))),
  });
}

const HAULER = 'hauler';

function ship(id, x, z, extra = {}) {
  return {
    id,
    modelId: HAULER,
    x,
    z,
    vx: extra.vx || 0,
    vz: extra.vz || 0,
    isPlayer: extra.isPlayer === true,
    role: extra.role || 'ship',
  };
}

function body(id, modelId, x, z, extra = {}) {
  return { id, modelId, x, z, vx: extra.vx || 0, vz: extra.vz || 0, ...extra };
}

