function tone(id, wave, freq, sweep, sweepTime, release, filterFreq) {
  return Object.freeze({
    id,
    category: 'world',
    type: 'oscillator',
    wave,
    baseFreq: freq,
    freqSweep: [freq, sweep],
    sweepTimeS: sweepTime,
    gainEnvelope: { attack: 0.01, sustain: 0.12, release },
    filterType: 'lowpass',
    filterFreq,
    filterQ: 0.7,
  });
}

