#!/usr/bin/env node
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('../', import.meta.url));
const DIR = join(ROOT, 'src/data/flavor');
const INDEX = join(DIR, 'index.generated.js');
const MODULE_RE = /^\d{3}-[a-z0-9-]+\.js$/;
const args = new Set(process.argv.slice(2));

const files = authoredFiles();
const rendered = renderIndex(files);
if (args.has('--check')) {
  const current = existsSync(INDEX) ? readFileSync(INDEX, 'utf8') : '';
  if (current !== rendered) {
    throw new Error('Flavor import graph is stale. Run: node scripts/build-flavor-index.mjs');
  }
  console.log(`Flavor index fresh: ${files.length} authored modules.`);
} else {
  if (!existsSync(INDEX) || readFileSync(INDEX, 'utf8') !== rendered) writeFileSync(INDEX, rendered, 'utf8');
  console.log(`Flavor index generated: ${files.length} authored modules.`);
}

function authoredFiles() {
  const jsFiles = readdirSync(DIR, { withFileTypes: true })
    .filter((entry) => entry.isFile() && entry.name.endsWith('.js'))
    .map((entry) => entry.name);
  const unexpected = jsFiles.filter((file) => !MODULE_RE.test(file) && !['catalog.js', 'index.generated.js'].includes(file));
  if (unexpected.length) throw new Error(`Unexpected flavor module filename(s): ${unexpected.join(', ')}`);
  return jsFiles.filter((file) => MODULE_RE.test(file)).sort((a, b) => a.localeCompare(b, 'en'));
}

function renderIndex(files) {
  const imports = files.map((file, index) => `import * as flavor${String(index + 1).padStart(3, '0')} from './${file}';`).join('\n');
  const records = files.map((file, index) => `  Object.freeze({ sourceFile: '${file}', namespace: flavor${String(index + 1).padStart(3, '0')} }),`).join('\n');
  return `// GENERATED by scripts/build-flavor-index.mjs — do not hand-edit.\n` +
    `// Browser ESM cannot enumerate directories; this deterministic graph is the scan result.\n` +
    `import { buildFlavorCatalog, buildFlavorSourceIndex, collectFlavorTextEntries } from './catalog.js';\n` +
    `${imports}\n\n` +
    `export const FLAVOR_MODULES = Object.freeze([\n${records}\n]);\n` +
    `export const FLAVOR_PACKS = buildFlavorCatalog(FLAVOR_MODULES);\n` +
    `export const FLAVOR_SOURCE_BY_REF = buildFlavorSourceIndex(FLAVOR_PACKS);\n` +
    `export const FLAVOR_TEXT_ENTRIES = collectFlavorTextEntries(FLAVOR_MODULES);\n`;
}
