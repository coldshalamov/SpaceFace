#!/usr/bin/env node
import assert from 'node:assert/strict';

import {
  assertBeatEntered,
  assertIncludesAll,
  assertNoRejectedActions,
  beatById,
  combatTraceHas,
  makeCombatCommand,
  readScenarioContract,
  runTrace,
  writeTapeWithCommands,
} from './lib/check-47a-common.mjs';

const contract = readScenarioContract();
const beat = beatById(contract, 'debris_sling');
assertIncludesAll(beat.requiredActors, ['player_kestrel', 'evidence_spindle_47a', 'carrier_wreck_bourse', 'scavenger_harasser'],
  'debris_sling actors');
assertIncludesAll(beat.requiredMechanics, ['massline.sling', 'debris.collision', 'shield.collapse'],
  'debris_sling mechanics');
assertIncludesAll(beat.presentationEventIds, ['shield.collapse', 'tether.near_break'],
  'debris_sling presentation events');

const defaultTrace = runTrace({
  ticks: 10000,
  events: 'combat:actionStarted,combat.*,tether.*,scenario.*',
  limit: 240,
});
assertBeatEntered(defaultTrace, 'debris_sling');
assert.equal(defaultTrace.scenarioContract.activeBeatId, 'debris_sling',
  'default 47-A tape should reach the debris_sling beat');
assert(defaultTrace.metrics.tetherAttached > 0, 'debris beat should be downstream of a real Massline attach');
assert(defaultTrace.metrics.projectileHits > 0, 'debris beat trace should retain projectile collision proof');

const probeTape = writeTapeWithCommands({
  id: '47a-debris-sling-probe',
  notes: ['Generated by check-47a-debris-sling: proves action_sling routes through SG-02 physics.'],
  commands: [
    { tick: 720, command: makeCombatCommand({ actionId: 'action_reel', attachment: 'latestOwned' }) },
    { tick: 722, command: makeCombatCommand({ actionId: 'action_sling', attachment: 'latestOwned' }) },
  ],
});

try {
  const slingTrace = runTrace({
    ticks: 5200,
    inputPath: probeTape.path,
    events: 'combat:actionStarted,combat.*,tether.*,scenario.*',
    limit: 260,
  });
  assertNoRejectedActions(slingTrace, '47-A debris sling probe');
  assert(slingTrace.metrics.tetherReel >= 2, 'sling probe should tighten the Massline before release');
  assert(combatTraceHas(slingTrace, 'physics.impulse', { actionId: 'action_sling' }),
    'sling probe should route action_sling through SG-02 physics.impulse');
  assert(slingTrace.metrics.projectileHits > 0, 'sling probe should preserve projectile collision proof');
  assert(slingTrace.metrics.combatDamage > 0, 'sling probe should preserve combat damage proof');
} finally {
  probeTape.cleanup();
}

console.log('47-A debris sling OK (beat reached and action_sling produced SG-02 physics impulse)');
