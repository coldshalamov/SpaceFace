#!/usr/bin/env node
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = fileURLToPath(new URL('../', import.meta.url));
const DIR = join(ROOT, 'src/data/encounters');
const INDEX = join(DIR, 'index.generated.js');
const PRESENTATION_INDEX = join(DIR, 'presentation.generated.js');
const MODULE_RE = /^\d{3,4}-[a-z0-9-]+\.js$/;
const args = new Set(process.argv.slice(2));
const PRESENTATION_FIELDS = Object.freeze([
  'id', 'title', 'tier', 'deck', 'script', 'fallbackScript', 'factionId', 'variant',
  'genuineChance', 'genuine', 'bait', 'civilian', 'context', 'predation', 'squad',
  'escort', 'warmAssets', 'claimVictim', 'bark', 'motive', 'engagementTrigger',
  'zoneTypes', 'anchorPoiId',
]);

const files = authoredFiles();
const rendered = renderIndex(files);
const renderedPresentation = await renderPresentationIndex(files);
if (args.has('--check')) {
  // The generated index is always written with LF. A Windows checkout with `core.autocrlf=true`
  // hands this freshness check a CRLF copy of byte-identical content, which used to fail as
  // "Encounter import graph is stale" on a tree with no drift at all (observed 2026-07-27: 93 CRLF
  // pairs, 93 extra bytes, otherwise character-for-character equal). `.gitattributes` pins the
  // checkout to LF; this normalisation makes the comparison correct even where that pin has not
  // been applied yet or a tool rewrote the file. Only line endings are normalised, so real
  // import-graph drift — an added, removed, or reordered module — still fails.
  const current = existsSync(INDEX) ? readFileSync(INDEX, 'utf8') : '';
  if (normalizeEol(current) !== normalizeEol(rendered)) {
    throw new Error('Encounter import graph is stale. Run: node scripts/build-encounter-index.mjs');
  }
  const currentPresentation = existsSync(PRESENTATION_INDEX)
    ? readFileSync(PRESENTATION_INDEX, 'utf8') : '';
  if (normalizeEol(currentPresentation) !== normalizeEol(renderedPresentation)) {
    throw new Error('Encounter presentation metadata is stale. Run: node scripts/build-encounter-index.mjs');
  }
  console.log(`Encounter indexes fresh: ${files.length} authored modules.`);
} else {
  if (!existsSync(INDEX) || readFileSync(INDEX, 'utf8') !== rendered) writeFileSync(INDEX, rendered, 'utf8');
  if (!existsSync(PRESENTATION_INDEX)
      || readFileSync(PRESENTATION_INDEX, 'utf8') !== renderedPresentation) {
    writeFileSync(PRESENTATION_INDEX, renderedPresentation, 'utf8');
  }
  console.log(`Encounter indexes generated: ${files.length} authored modules.`);
}

function normalizeEol(text) {
  return text.replace(/\r\n/g, '\n');
}

function authoredFiles() {
  return readdirSync(DIR, { withFileTypes: true })
    .filter((entry) => entry.isFile() && MODULE_RE.test(entry.name))
    .map((entry) => entry.name)
    // Numeric order first so a four-digit block (1200-1299) appends after 901 instead of renumbering.
    .sort((a, b) => (parseInt(a, 10) - parseInt(b, 10)) || a.localeCompare(b, 'en'));
}

function renderIndex(files) {
  const imports = files.map((file, index) => `import * as encounter${String(index + 1).padStart(3, '0')} from './${file}';`).join('\n');
  const names = files.map((_, index) => `  encounter${String(index + 1).padStart(3, '0')},`).join('\n');
  return `// GENERATED by scripts/build-encounter-index.mjs — do not hand-edit.\n` +
    `// Browser ESM cannot enumerate directories; this deterministic import graph is the scan result.\n` +
    `import { buildEncounterCatalog } from './catalog.js';\n` +
    `${imports}\n\n` +
    `export const ENCOUNTER_MODULES = Object.freeze([\n${names}\n]);\n` +
    `export const ENCOUNTERS = buildEncounterCatalog(ENCOUNTER_MODULES);\n`;
}

async function renderPresentationIndex(files) {
  const moduleUrls = files.map((file) => pathToFileURL(join(DIR, file)).href);
  const authoredModules = await Promise.all(moduleUrls.map((url) => import(url)));
  const { NAMED_CAPTAINS } = await import(pathToFileURL(join(ROOT, 'src/data/encounters.js')).href);
  const encounters = {};
  const selfRegisteredEncounterIds = [];
  for (const module of authoredModules) {
    const authored = module && module.default;
    if (!authored || typeof authored.id !== 'string') continue;
    const metadata = {};
    for (const field of PRESENTATION_FIELDS) {
      if (Object.hasOwn(authored, field)) metadata[field] = authored[field];
    }
    // Round-trip through JSON here enforces the data-only boundary. Runtime callbacks remain
    // in the full simulation index and never enter this presentation view.
    encounters[authored.id] = JSON.parse(JSON.stringify(metadata));
    if (module.runtime) selfRegisteredEncounterIds.push(authored.id);
  }
  const metadata = {
    schemaVersion: 1,
    fields: PRESENTATION_FIELDS,
    encounters,
    namedCaptains: JSON.parse(JSON.stringify(NAMED_CAPTAINS)),
    selfRegisteredEncounterIds,
  };
  const serialized = JSON.stringify(metadata);
  return `// GENERATED by scripts/build-encounter-index.mjs — do not hand-edit.\n`
    + `// Data-only encounter fields consumed by main-thread presentation decode warming.\n`
    + `const DATA_JSON = ${JSON.stringify(serialized)};\n`
    + `export const ENCOUNTER_PRESENTATION_METADATA = Object.freeze(JSON.parse(DATA_JSON));\n`;
}
