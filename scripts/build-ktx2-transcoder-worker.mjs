#!/usr/bin/env node
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { KTX2Loader } from 'three/addons/loaders/KTX2Loader.js';

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const BASIS_SOURCE = resolve(ROOT, 'vendor/addons/libs/basis/basis_transcoder.js');
const WORKER_OUTPUT = resolve(ROOT, 'vendor/addons/libs/basis/basis_transcoder.worker.js');

export async function createKtx2TranscoderWorkerSource({ basisSource } = {}) {
  const basis = basisSource == null ? await readFile(BASIS_SOURCE, 'utf8') : String(basisSource);
  const workerFunction = KTX2Loader.BasisWorker.toString();
  const workerBody = workerFunction.slice(
    workerFunction.indexOf('{') + 1,
    workerFunction.lastIndexOf('}'),
  );
  return [
    '// Generated by scripts/build-ktx2-transcoder-worker.mjs. Do not edit by hand.',
    `let _EngineFormat = ${JSON.stringify(KTX2Loader.EngineFormat)};`,
    `let _EngineType = ${JSON.stringify(KTX2Loader.EngineType)};`,
    `let _TranscoderFormat = ${JSON.stringify(KTX2Loader.TranscoderFormat)};`,
    `let _BasisFormat = ${JSON.stringify(KTX2Loader.BasisFormat)};`,
    basis.trim(),
    workerBody.trim(),
    '',
  ].join('\n');
}

async function main(argv = process.argv.slice(2)) {
  const unknown = argv.filter((arg) => arg !== '--check');
  if (unknown.length) throw new Error(`Unknown KTX2 worker option: ${unknown.join(', ')}`);
  const expected = await createKtx2TranscoderWorkerSource();
  if (argv.includes('--check')) {
    const current = await readFile(WORKER_OUTPUT, 'utf8').catch(() => '');
    if (current !== expected) throw new Error('basis_transcoder.worker.js is stale; rebuild it.');
    console.log('ktx2-transcoder-worker: fresh');
    return;
  }
  await writeFile(WORKER_OUTPUT, expected, 'utf8');
  console.log('ktx2-transcoder-worker: built');
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await main();
}
