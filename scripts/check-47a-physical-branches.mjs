#!/usr/bin/env node
import assert from 'node:assert/strict';

import {
  assertIncludesAll,
  beatById,
  branchById,
  proofMetricById,
  readScenarioContract,
  runTrace,
  traceHas,
  writeTapeWithCommands,
} from './lib/check-47a-common.mjs';

const contract = readScenarioContract();
const resolution = beatById(contract, 'resolution_branch');
const expectedBranches = ['escape_with_evidence', 'surrender_evidence', 'destroy_evidence', 'deliver_to_contact'];
assert.deepEqual(resolution.branchIds, expectedBranches, 'resolution_branch should enumerate every authored outcome');
assertIncludesAll(resolution.requiredMechanics, ['scenario.branch_resolution', 'world_fact.apply', 'replay.branch_policy'],
  'resolution_branch mechanics');
assertIncludesAll(resolution.proofMetricIds, ['policy_completion_count', 'branch_world_fact_delta'],
  'resolution_branch proof metrics');
assert.equal(proofMetricById(contract, 'branch_world_fact_delta').required, true,
  'branch world fact delta proof should be required');

for (const branchId of expectedBranches) {
  const branch = branchById(contract, branchId);
  assert.equal(branch.unlockedByBeat, 'resolution_branch', `${branchId} should unlock at resolution_branch`);
  assert(branch.policyId && branch.policyId.startsWith('policy.47a.'), `${branchId} should keep a policy id`);
  assert((branch.worldFactEffects || []).length >= 3, `${branchId} should change at least three world facts`);
  for (const effect of branch.worldFactEffects || []) {
    assert(effect.factId && effect.factId.startsWith('fact.47a.'), `${branchId} fact effect should target a 47-A fact`);
    assert.equal(effect.op, 'set', `${branchId} fact effect should be a deterministic set`);
    assert.notEqual(effect.value, 'unresolved', `${branchId} should resolve facts away from unresolved`);
  }
}

for (const branchId of ['surrender_evidence', 'deliver_to_contact']) {
  const branch = branchById(contract, branchId);
  assert.equal(branch.resolutionPredicate?.source, 'live-state', `${branchId} should have a live-state predicate`);
  assert((branch.resolutionPredicate.all || []).some((condition) => condition.kind === 'attachmentActive'
    && condition.targetActorId === 'evidence_spindle_47a'),
  `${branchId} should require an active physical Massline on the evidence`);
  assert((branch.resolutionPredicate.all || []).some((condition) => condition.kind === 'actorDistance'),
    `${branchId} should require physical proximity to the handoff target`);
}

const completed = [];
for (const branchId of expectedBranches) {
  const branch = branchById(contract, branchId);
  const probeTape = writeTapeWithCommands({
    id: `47a-physical-branch-${branchId}`,
    notes: [`Generated by check-47a-physical-branches: resolves ${branchId} through the SG-05 branch helper.`],
    dropScenarioBranches: true,
    commands: [{
      tick: 36010,
      command: {
        kind: 'scenarioBranch',
        branchId,
        source: branch.policyId,
      },
    }],
  });
  try {
    const result = runTrace({
      ticks: 36120,
      inputPath: probeTape.path,
      events: 'scenario.*,combat.*,tether.*',
      limit: 520,
    });
    assert.equal(result.scenarioContract.activeBeatId, 'resolution_branch',
      `${branchId} should reach the resolution beat`);
    assert.equal(result.scenarioContract.resolvedBranchId, branchId,
      `${branchId} should resolve through the scenario branch helper`);
    assert.equal(result.scenarioContract.resolution.source, branch.policyId,
      `${branchId} should retain the branch policy source`);
    assert.equal(result.metrics.scenarioBranchResolved, 1,
      `${branchId} should emit exactly one branch resolution`);
    assert.equal(result.metrics.scenarioFactChanged, branch.worldFactEffects.length,
      `${branchId} should apply every authored world fact effect`);
    assert(traceHas(result, 'scenario:branchResolved', (record) => record.payload?.branchId === branchId),
      `${branchId} should emit branch resolution trace evidence`);
    for (const effect of branch.worldFactEffects || []) {
      assert.equal(result.scenarioContract.factValues[effect.factId], effect.value,
        `${branchId} should set ${effect.factId} to ${effect.value}`);
    }
    completed.push(branchId);
  } finally {
    probeTape.cleanup();
  }
}

console.log(`47-A physical branches OK (${completed.join(', ')})`);
