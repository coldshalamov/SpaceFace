// build_icons — the kit's 86-glyph filled family, as one importable module.
//
// Source of truth: the produced sprites under assets/ui/kit/icons/ (Blender-era construction
// grammar; see assets/ui/kit/README.md). Each <symbol> holds a body path in currentColor and an
// `.accent` path the consumer tints separately. This script lifts the symbol bodies verbatim —
// no redrawing — into src/ui/deckplate/iconPaths.js so any surface can inline an icon (inline
// SVG survives forced colours; CSS background images do not).
//
//   node assets/ui/deckplate/tools/build_icons.mjs
//
// Keys keep the sprite's `icon-` prefix on purpose: the localization extractor treats object keys
// such as `line` or `text` as player copy (scripts/localization-surfaces.json recognizedCopyFields).

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('../../../../', import.meta.url));
const SIZES = [24, 48];

function symbols(size) {
  const svg = readFileSync(`${ROOT}assets/ui/kit/icons/_sprite-${size}.svg`, 'utf8');
  const out = {};
  const re = /<symbol id="(icon-[a-z0-9-]+)" viewBox="0 0 (\d+) \2">([\s\S]*?)<\/symbol>/g;
  let m;
  while ((m = re.exec(svg))) out[m[1]] = m[3].replace(/\s+/g, ' ').trim();
  return out;
}

const tables = Object.fromEntries(SIZES.map((s) => [s, symbols(s)]));
const names = Object.keys(tables[24]).sort();
for (const s of SIZES) {
  const missing = names.filter((n) => !tables[s][n]);
  if (missing.length) throw new Error(`sprite ${s} is missing ${missing.join(', ')}`);
}

const lines = [
  '// GENERATED by assets/ui/deckplate/tools/build_icons.mjs from assets/ui/kit/icons/_sprite-{24,48}.svg.',
  '// Do not edit by hand: re-run the script. Path data is the produced kit family, verbatim.',
  '',
];
for (const s of SIZES) {
  lines.push(`export const DP_ICON_${s} = Object.freeze({`);
  for (const n of names) lines.push(`  '${n}': '${tables[s][n].replace(/'/g, "\\'")}',`);
  lines.push('});', '');
}
writeFileSync(`${ROOT}src/ui/deckplate/iconPaths.js`, lines.join('\n'));
console.log(`iconPaths.js: ${names.length} glyphs x ${SIZES.length} sizes`);
