import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createSimHost } from '../scripts/lib/simWorkerHost.mjs';
import { createSimCommandRing } from '../scripts/lib/simCommandChannel.mjs';
import { createDomainMirroringProfile, applyDomainPathUpdate } from '../scripts/lib/simReadModel.mjs';
import { createGameState } from '../src/core/gameState.js';
import { createBus } from '../src/core/eventBus.js';
import { MAIN_TO_SIM_BUS_EVENTS } from '../src/core/mainToSimEventSurface.js';
import { automationScreen } from '../src/ui/screens/automationPanel.js';
import { fakeDom } from './helpers/fake-dom.mjs';
import { makeShipEntitySpec, fittingsFromDefaultModules } from '../src/systems/ships.js';
import { quoteYardOperation } from '../src/shipjack/yardOperations.js';
import { quoteFleetOperation } from '../src/shipjack/fleetOperations.js';

test('a secured hull joins the wing, survives Continue, and returns to its receiving berth', async () => {
  const host = createSimHost(), main = createGameState(4242), domains = new Map(Object.entries(main));
  const oldDocument = globalThis.document; let screen;
  let serial = 0;
  const apply = reply => { for (const u of reply.domainUpdates || []) {
    const segs = u.segs.length === 1 && u.segs[0].includes('.') ? u.segs[0].split('.') : u.segs;
    applyDomainPathUpdate(domains, { ...u, segs }, new Set()); main[segs[0]] = domains.get(segs[0]);
  }};
  const tick = async (commands = [], steps = 0) => {
    const reply = structuredClone(await host.tick({ tick: ++serial, steps, commands })); apply(reply); return reply;
  };
  const send = async (emit, payload) => { const ring = createSimCommandRing(); ring.pushBus({ emit, payload }); return tick(ring.drain()); };
  try {
    apply(structuredClone(await host.init({ profile: 'production', seed: 4242, bridgeAll: true,
      domainMirroring: createDomainMirroringProfile('station'),
      scenarioContract: JSON.parse(readFileSync('src/data/scenarios/47a.scenario.json', 'utf8')) })));
    const { state, registry, runtime, bus } = host.host;
    state.mode = 'flight'; state.run.kind = 'adventure'; state.onboarding = { active: false, finished: true };
    registry.get('world').enterSector('sector_helios_prime');
    const jack = registry.get('shipjack'), ships = registry.get('ships'), automation = registry.get('automation');
    const station = jack.stationEntity('station_helios'); assert.ok(station);
    const player = runtime.spawn(makeShipEntitySpec('ship_kestrel', { isPlayer: true, pos: { x: station.pos.x + station.radius + 60, z: station.pos.z }, fittings: [] }));
    state.playerId = player.id;
    state.player.ownedShips = [{ defId: 'ship_kestrel', fittings: [] }]; state.player.activeShipIndex = 0;
    const fittings = fittingsFromDefaultModules('ship_wasp', ['mod_engine_ion_m']);
    const prize = runtime.spawn(makeShipEntitySpec('ship_wasp', { team: 2, pos: { x: player.pos.x, z: player.pos.z + 60 }, fittings, ai: { fsm: 'surrender' } }));
    prize.shield = 0; prize.hull = 30; prize.armorMax = 20; prize.armorHp = 6;
    prize.data.cargo = { items: { cmdty_ore_iron: 7 }, usedVolume: 7, usedMass: 7, capVolume: 40 };
    const vessel = jack.admit(prize, { origin: 'tracked-test', name: 'Prize', ownerId: 'former-crew', crew: 'evacuated' });
    const attempt = jack.attempt(vessel, prize); attempt.phase = 'foothold'; attempt.dwell = 1.6; attempt.surrendered = true; attempt.scanned = true;
    const secured = jack.command({ action: 'helm', targetId: prize.id, generation: vessel.generation });
    assert.equal(secured.ok, true, secured.reason);
    const id = vessel.vesselId, generation = vessel.generation, owned = state.player.ownedShips[1];
    const instances = structuredClone(owned.fittedInstances), cargo = structuredClone(owned.cargo);
    const drive = state.combat.entities[String(prize.id)]?.subsystems?.subsystem_drive;
    assert.ok(drive); drive.health = 9; drive.effectiveDisabled = true;
    state.ui.docked = true; state.ui.dockedStationId = 'station_helios'; bus.emit('dock:docked', { stationId: 'station_helios' });
    assert.equal(vessel.location.kind, 'berth');
    await tick();
    state.player.shipjack.yards[id] = { operationId: 'yard:busy' };
    const busy = await send('ui:fleetOrder', { order: 'assignFleet', targetRef: 1 });
    assert.ok(busy.events.some(e => e.t === 'automation:fleetChanged' && e.p.action === 'assignmentRejected'));
    assert.equal(owned.fleetAssignmentId, undefined);
    delete state.player.shipjack.yards[id];
    state.player.shipjack.fleetOperations ||= {};
    state.player.shipjack.fleetOperations[id] = { operationId: 'tug:busy' };
    const busyTug = await send('ui:fleetOrder', { order: 'assignFleet', targetRef: 1 });
    assert.ok(busyTug.events.some(e => e.t === 'automation:fleetChanged' && e.p.action === 'assignmentRejected'));
    assert.equal(owned.fleetAssignmentId, undefined);
    delete state.player.shipjack.fleetOperations[id];
    for (let i = 0; i < 70 && (!main.player.shipjack?.vesselsById?.[id] || main.player.shipjack?.fleetOperations?.[id]); i++) await tick();
    const doc = fakeDom(); doc.createDocumentFragment = () => doc._make('fragment'); globalThis.document = doc;
    const root = doc._make('div'), body = doc._make('div'), tabs = doc._make('div');
    root.querySelector = s => s === '[data-body]' ? body : s === '[data-tabs]' ? tabs : null;
    body.replaceChildren = (...nodes) => { body.children = nodes; };
    const mainBus = createBus(), ring = createSimCommandRing();
    assert.ok(MAIN_TO_SIM_BUS_EVENTS.has('ui:fleetOrder'));
    mainBus.on('ui:fleetOrder', p => ring.pushBus({ emit: 'ui:fleetOrder', payload: p }));
    screen = Object.create(automationScreen); screen._tab = 'fleet';
    screen.mount(root, { state: main, bus: mainBus }); screen.refresh();
    const html = () => body.children.flatMap(fragment => fragment.children).map(n => n.innerHTML).join('\n');
    assert.match(html(), /data-act="assignFleet" data-ref="1"/, `the actual fleet panel offers the berthed tracked hull: ${JSON.stringify({ docked: main.ui?.docked, station: main.ui?.dockedStationId, owned: main.player?.ownedShips, vessel: main.player?.shipjack?.vesselsById?.[id], fleet: main.automation?.fleet })}`);
    const control = { dataset: { act: 'assignFleet', ref: '1', kind: 'ownedShip' } };
    for (const fn of body.listeners.click || []) fn({ target: { closest: () => control } });
    const assigned = await tick(ring.drain());
    for (const event of assigned.events || []) mainBus.emit(event.t, event.p);
    assert.ok(assigned.events.some(e => e.t === 'automation:fleetChanged' && e.p.action === 'assigned'), JSON.stringify({ events: assigned.events, ui: state.ui, v: vessel, found: !!jack.stationEntity('station_helios') }));
    assert.doesNotMatch(html(), /data-act="assignFleet" data-ref="1"/, 'the acknowledged hull leaves the available roster');
    const row = state.automation.fleet[0]; assert.equal(owned.fleetAssignmentId, row.id);
    assert.match(quoteYardOperation(state, { vesselId: id, action: 'sell' }).reason, /Return this wingman/);
    assert.match(quoteFleetOperation(state, { vesselId: id, action: 'recover', stationId: 'station_helios' }).reason, /Return this wingman/);
    state.ui.docked = false; state.ui.dockedStationId = null;
    await send('dock:undocked', { committed: true, stationId: 'station_helios' });
    await tick([], 1);
    let wing = state.entities.get(row._liveId); assert.ok(wing?.alive, 'undocking materializes the actual assigned vessel');
    assert.equal(wing.data.vesselId, id); assert.equal(wing.data.shipjackGeneration, generation);
    assert.equal(wing.hull, 30); assert.equal(wing.armorHp, 6);
    assert.deepEqual(owned.fittedInstances, instances); assert.deepEqual(owned.cargo, cargo);
    assert.equal(state.entityList.filter(e => e.alive && e.data?.vesselId === id).length, 1);

    // The actual save request emits save:started before serializing the player.
    wing.hull = 22;
    const saver = registry.get('save');
    // Save's public request owns the snapshot boundary; retain the resulting envelope for restore below.
    const saved = await send('game:save', { slot: 'tracked-wing' });
    assert.ok(saved.events.some(e => e.t === 'save:started'));
    assert.equal(state.player.shipjack.vesselsById[id].parkedBody.hull, 22);
    const stored = saved.storageOps?.find(op => op.key === 'sf.save.tracked-wing' && op.op === 'set');
    assert.ok(stored, JSON.stringify(saved.storageOps?.map(op => ({ op: op.op, key: op.key }))));
    const current = JSON.parse(stored.value);
    assert.equal(saver.loadEnvelope(JSON.parse(JSON.stringify(current)), 'tracked-wing'), true);
    state.mode = 'flight';
    await tick([], 1);
    const restoredRow = state.automation.fleet.find(r => r.id === row.id);
    wing = state.entities.get(restoredRow?._liveId);
    assert.ok(wing?.alive, `Continue restores the assigned body: ${JSON.stringify({ row: restoredRow, ui: state.ui?.docked, player: state.playerId, vessel: state.player.shipjack?.vesselsById[id]?.location })}`);
    assert.equal(wing.data.vesselId, id); assert.equal(wing.hull, 22);
    assert.equal(wing.armorMax, 20); assert.equal(wing.armorHp, 6);
    assert.equal(state.player.shipjack.vesselsById[id].crew, 'evacuated');
    assert.equal(state.combat.entities[String(wing.id)].subsystems.subsystem_drive.health, 9);
    assert.equal(state.entityList.filter(e => e.alive && e.data?.vesselId === id).length, 1);
    registry.get('world').enterSector('sector_ceres_belt');
    await tick([], 1);
    wing = state.entities.get(restoredRow._liveId);
    assert.ok(wing?.alive, 'the tracked wingman follows the actual sector transition');
    assert.equal(wing.data.vesselId, id); assert.equal(wing.hull, 22);
    assert.equal(state.entityList.filter(e => e.alive && e.data?.vesselId === id).length, 1);
    registry.get('world').enterSector('sector_helios_prime');
    await tick([], 1);
    wing = state.entities.get(restoredRow._liveId); assert.ok(wing?.alive);
    for (let i = 0; i < 70 && main.player.shipjack?.vesselsById?.[id]?.location?.kind !== 'field'; i++) await tick();
    assert.equal(main.player.shipjack?.vesselsById?.[id]?.location?.kind, 'field');
    const restoredStation = jack.stationEntity('station_helios');
    wing.pos.x = restoredStation.pos.x + restoredStation.radius + 500; wing.pos.z = restoredStation.pos.z;
    state.ui.docked = true; state.ui.dockedStationId = 'station_helios'; bus.emit('dock:docked', { stationId: 'station_helios' });
    const refused = await send('ui:fleetOrder', { order: 'releaseFleet', shipId: restoredRow.id });
    assert.ok(refused.events.some(e => e.t === 'automation:fleetChanged' && e.p.reason === 'tracked_not_berthed'));
    assert.ok(wing.alive); assert.equal(state.player.ownedShips.find(s => s.vesselId === id).fleetAssignmentId, restoredRow.id);
    wing.pos.x = restoredStation.pos.x + 60; wing.pos.z = restoredStation.pos.z;
    wing.vel.x = 0; wing.vel.z = 0;
    const liveGeneration = wing.data.shipjackGeneration;
    wing.data.shipjackGeneration = 'stale:generation';
    const stale = await send('ui:fleetOrder', { order: 'releaseFleet', shipId: restoredRow.id });
    assert.ok(stale.events.some(e => e.t === 'automation:fleetChanged' && e.p.reason === 'tracked_not_berthed'));
    assert.ok(wing.alive); assert.equal(state.automation.fleet[0], restoredRow);
    wing.data.shipjackGeneration = liveGeneration;
    screen.refresh();
    assert.match(html(), /data-act="releaseFleet"/, 'the actual fleet panel offers Return to hangar');
    const returnControl = { dataset: { act: 'releaseFleet', ref: restoredRow.id, kind: 'fleet' } };
    for (const fn of body.listeners.click || []) fn({ target: { closest: () => returnControl } });
    const returned = await tick(ring.drain());
    for (const event of returned.events || []) mainBus.emit(event.t, event.p);
    const restoredOwned = state.player.ownedShips.find(s => s.vesselId === id), restoredVessel = state.player.shipjack.vesselsById[id];
    assert.equal(restoredOwned.fleetAssignmentId, undefined);
    assert.equal(restoredVessel.location.kind, 'berth'); assert.equal(restoredVessel.location.stationId, 'station_helios');
    assert.equal(main.player.shipjack.vesselsById[id].location.kind, 'berth', 'the return receipt publishes current Registry custody to the main panel');
    assert.equal(restoredVessel.parkedBody.hull, 22);
    assert.deepEqual(restoredOwned.fittedInstances, instances);
    assert.deepEqual(restoredOwned.cargo.items, cargo.items);
    assert.equal(restoredOwned.cargo.usedVolume, cargo.usedVolume);

    // A legacy generic condition cache can be older than the Registry's physical
    // hull. Repair the actual tracked ship through the paid berth service, then
    // prove neither stale cache can override that work on another deployment.
    restoredOwned.parkedBody = { hull: 0, armorHp: 0, armorMax: 20 };
    state.player.credits = 50000;
    assert.equal(ships.setActiveShip(state.player.ownedShips.indexOf(restoredOwned)), true);
    const active = state.entities.get(state.playerId), beforeCredits = state.player.credits;
    assert.equal(active.hull, 22); assert.equal(active.armorHp, 6); assert.equal(active.armorMax, 20);
    await send('ui:service', { type: 'repair' });
    assert.ok(state.player.credits < beforeCredits, 'the canonical yard charges for the repair');
    const yard = registry.get('stationServices'); state.timeScale = 0;
    for (let i = 0; i < 300 && yard.pendingPlayerService('repair').hull + yard.pendingPlayerService('repair').armor > 0; i++) yard.update(1, state);
    assert.ok(active.hull > 22, 'the paid yard actually repairs the active tracked hull');
    assert.ok(active.armorHp > 6, 'the paid yard actually repairs its armor');
    active.shield = Math.min(4, active.shieldMax); active.cap = Math.min(7, active.capMax);
    const repaired = { hull: active.hull, armorHp: active.armorHp, armorMax: active.armorMax, shield: active.shield, cap: active.cap };
    assert.equal(ships.setActiveShip(0), true);
    assert.equal(restoredVessel.parkedBody.hull, repaired.hull, 'the Registry captured the paid physical repair');
    const second = await send('ui:fleetOrder', { order: 'assignFleet', targetRef: state.player.ownedShips.indexOf(restoredOwned) });
    assert.ok(second.events.some(e => e.t === 'automation:fleetChanged' && e.p.action === 'assigned'), 'a stale zero cache does not reject a repaired Registry vessel');
    const nextRow = state.automation.fleet[0]; nextRow.parkedBody = { hull: 0, armorHp: 0, armorMax: 20 };
    state.ui.docked = false; state.ui.dockedStationId = null; state.timeScale = 1;
    await send('dock:undocked', { committed: true, stationId: 'station_helios' }); await tick([], 1);
    const repairedWing = state.entities.get(nextRow._liveId); assert.ok(repairedWing?.alive);
    for (const [key, value] of Object.entries(repaired)) assert.equal(repairedWing[key], value, `${key} comes from the repaired Registry body`);
  } finally { screen?.dispose(); globalThis.document = oldDocument; host.shutdown(); }
});
